// src/emit/versions/versionTypes.ts
// One TypeScript type per model and enum per published version of a schema, such
// as `Contact_0_4_0`, so an app can write the steps that migrate a row from one
// version to the next with both sides typed. The types are the codec target's
// types of that version: the native values the SDK reads and writes.

import type { EnumDecl } from "../../parser/ast.js";
import type { ResolvedSchema } from "../../resolver/types.js";
import { planModel, renderTsType, isOptional, type FieldPlan, type ModelPlan, type ValueShape } from "../codec/plan.js";
import { FILE_MESSAGE_NAME } from "../codec/plan.js";

export interface VersionedSchema {
  /** `major.minor.patch`. */
  version: string;
  schema:  ResolvedSchema;
}

export class VersionTypesError extends Error {}

/** `Contact` at 0.4.0 is `Contact_0_4_0`. */
export function versionedName(name: string, version: string): string {
  return `${name}_${version.split(".").join("_")}`;
}

/** The module text; `codecModule` is imported from for the built-in File type. */
export function emitVersionTypes(versions: VersionedSchema[], codecModule: string | undefined): string {
  const blocks = ["// Generated by openschema (versions target). Do not edit."];
  const sections = versions.map(versioned => versionSection(versioned));
  if (sections.some(section => section.usesFile)) {
    blocks.push(fileImport(codecModule));
  }
  blocks.push(...sections.map(section => section.text));
  return `${blocks.join("\n\n")}\n`;
}

function fileImport(codecModule: string | undefined): string {
  if (codecModule === undefined) {
    throw new VersionTypesError("a version uses File, so run the codec target in the same command");
  }
  return `import type { ${FILE_MESSAGE_NAME} } from './${codecModule}'`;
}

interface Section {
  text:     string;
  usesFile: boolean;
}

function versionSection(versioned: VersionedSchema): Section {
  const enums = [...versioned.schema.enums.values()].map(symbol =>
    versionedEnum(symbol.decl as EnumDecl, versioned.version));
  const plans = [...versioned.schema.records.values()]
    .filter(record => !record.isGeneric)
    .map(record => planModel(record, record.fields.filter(field => !field.isPrivate), versioned.schema));
  const interfaces = plans.map(plan => versionedInterface(plan, versioned.version));
  const text = [`// ── ${versioned.version} ──`, ...enums, ...interfaces].join("\n\n");
  return { text, usesFile: plans.some(plan => plan.fields.some(field => holdsFile(field.value))) };
}

function versionedEnum(decl: EnumDecl, version: string): string {
  const members = decl.variants.map(variant => `  ${variant.name} = ${variant.ordinal},`);
  return [`export enum ${versionedName(decl.name, version)} {`, ...members, "}"].join("\n");
}

function versionedInterface(plan: ModelPlan, version: string): string {
  const lines = plan.fields.map(field => versionedProperty(field, version));
  return [`export interface ${versionedName(plan.name, version)} {`, ...lines, "}"].join("\n");
}

function versionedProperty(field: FieldPlan, version: string): string {
  let optional = "";
  if (isOptional(field.container)) optional = "?";
  const type = renderTsType(field.container, versionedShape(field.value, version));
  return `  ${propertyName(field.name)}${optional}: ${type};`;
}

/** Message and enum references point at the same version's types. */
function versionedShape(value: ValueShape, version: string): ValueShape {
  if (value.kind === "message" || value.kind === "enum") {
    return { ...value, name: versionedName(value.name, version) };
  }
  if (value.kind !== "oneof") return value;
  const variants = value.variants.map(variant => ({ ...variant, value: versionedShape(variant.value, version) }));
  return { kind: "oneof", variants };
}

function holdsFile(value: ValueShape): boolean {
  if (value.kind === "file") return true;
  if (value.kind !== "oneof") return false;
  return value.variants.some(variant => holdsFile(variant.value));
}

function propertyName(name: string): string {
  if (/^[A-Za-z_][A-Za-z0-9_]*$/.test(name)) return name;
  return JSON.stringify(name);
}
