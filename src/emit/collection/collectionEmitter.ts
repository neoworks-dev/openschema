// src/emit/collection/collectionEmitter.ts
// The `collection` target: the module an app hands to `neoworks.collection()`. It
// pairs the registry path and version of the schema (from openschema.yaml beside
// it) with the descriptor text exactly as `openschema publish` uploads it, so the descriptor
// an app bundles and the one the registry serves are the same bytes. When the codec
// module is generated too, the export also carries the content type of every
// table and which single references point at which table, so the SDK can type the
// resources and `include` it builds from the descriptor.

import { buildDescriptor, definesNeoworksTables, publishedDescriptor } from "../descriptor/descriptorEmitter.js";
import type { SchemaDescriptor } from "../descriptor/descriptorTypes.js";
import type { EmitContext, Emitter, OutputFile } from "../types.js";

export const COLLECTION_FILE = "index.ts";

/** The context option naming the collection, `@scope/name`; the CLI fills it from the manifest. */
export const COLLECTION_OPTION = "collection";

/** The context option holding the schema version, `major.minor.patch`; the CLI fills it from the manifest. */
export const COLLECTION_VERSION_OPTION = "collectionVersion";

/** The context option naming the codec module to re-export, set when the codec target runs too. */
export const CODEC_MODULE_OPTION = "codecModule";

/** The context option naming the versions module to re-export, set when the versions target runs too. */
export const VERSIONS_MODULE_OPTION = "versionsModule";

export class CollectionTargetError extends Error {}

export const collectionEmitter: Emitter = {
  target: "collection",
  fileExtension: "ts",

  emit(context: EmitContext): OutputFile[] {
    const name = context.options[COLLECTION_OPTION];
    const version = context.options[COLLECTION_VERSION_OPTION];
    if (name === undefined || version === undefined) {
      throw new CollectionTargetError("the collection target needs the schema's registry path and version; run it through the CLI with an openschema.yaml beside the schema");
    }
    if (!definesNeoworksTables(context.schema)) {
      throw new CollectionTargetError("the collection target needs a schema that defines @neoworks.table models");
    }
    const descriptor = buildDescriptor({ schema: context.schema, company: null, includePrivate: false, options: {} });
    const typing = { models: descriptor.tables.map((table) => table.model), references: referencesOf(descriptor) };
    const identity = { name, version };
    const contents = collectionModule(identity, publishedDescriptor(context.schema), typing, context.options[CODEC_MODULE_OPTION]);
    return [{ path: COLLECTION_FILE, contents: withVersionsExport(contents, context.options[VERSIONS_MODULE_OPTION]) }];
  },
};

/** The versions module adds its types to the module's exports, after the header line. */
function withVersionsExport(contents: string, versionsModule: string | undefined): string {
  if (versionsModule === undefined) return contents;
  const [header, ...rest] = contents.split("\n");
  return [header, `export * from './${versionsModule}'`, ...rest].join("\n");
}

interface Identity {
  name:    string;
  version: string;
}

/** The type-level facts of a collection: its tables and, per table, the target of each single reference field. */
interface Typing {
  models:     string[];
  references: Map<string, Map<string, string>>;
}

/** Only tables with a single `ref<T>` field appear; the core includes single references only. */
export function referencesOf(descriptor: SchemaDescriptor): Map<string, Map<string, string>> {
  const references = new Map<string, Map<string, string>>();
  for (const table of descriptor.tables) {
    const targets = referenceTargetsOf(descriptor, table.model);
    if (targets.size > 0) references.set(table.model, targets);
  }
  return references;
}

function referenceTargetsOf(descriptor: SchemaDescriptor, modelName: string): Map<string, string> {
  const targets = new Map<string, string>();
  const model = descriptor.models.find((candidate) => candidate.name === modelName);
  if (model === undefined) return targets;
  for (const field of model.fields) {
    if (field.value.kind !== "ref" || field.container.kind !== "singular") continue;
    targets.set(field.name, localNameOf(field.value.model));
  }
  return targets;
}

function localNameOf(qualifiedName: string): string {
  return qualifiedName.slice(qualifiedName.lastIndexOf(".") + 1);
}

function collectionModule(identity: Identity, descriptor: string, typing: Typing, codecModule: string | undefined): string {
  const lines = ["// Generated by openschema (collection target). Do not edit."];
  if (codecModule === undefined) {
    lines.push("", ...untypedCollection(identity, descriptor));
  } else {
    lines.push(`export * from './${codecModule}'`, `import type { ${typing.models.join(", ")} } from './${codecModule}'`, "", ...typedCollection(identity, descriptor, typing));
  }
  lines.push("", "export default collection", "");
  return lines.join("\n");
}

function untypedCollection(identity: Identity, descriptor: string): string[] {
  return [
    "/** Pass to `Neoworks.collection`; the descriptor text is exactly what the registry publishes. */",
    "export const collection = {",
    `\tname: '${identity.name}',`,
    `\tversion: '${identity.version}',`,
    `\tdescriptor: ${JSON.stringify(descriptor)},`,
    "} as const",
  ];
}

/**
 * The `tables` and `references` members exist only in the type: they tell the SDK which content
 * type each table has and which table each single reference field points to.
 */
function typedCollection(identity: Identity, descriptor: string, typing: Typing): string[] {
  const lines = [
    "/** Pass to `Neoworks.collection`; the descriptor text is exactly what the registry publishes. */",
    "export const collection = {",
    `\tname: '${identity.name}',`,
    `\tversion: '${identity.version}',`,
    `\tdescriptor: ${JSON.stringify(descriptor)},`,
    "} as {",
    `\treadonly name: '${identity.name}'`,
    `\treadonly version: '${identity.version}'`,
    "\treadonly descriptor: string",
  ];
  lines.push(`\treadonly tables?: { ${typing.models.map((model) => `${model}: ${model}`).join("; ")} }`);
  if (typing.references.size > 0) lines.push(`\treadonly references?: ${referencesType(typing.references)}`);
  lines.push("}");
  return lines;
}

function referencesType(references: Map<string, Map<string, string>>): string {
  const tables = [...references].map(([table, targets]) => `${table}: { ${[...targets].map(([field, target]) => `${field}: '${target}'`).join("; ")} }`);
  return `{ ${tables.join("; ")} }`;
}
