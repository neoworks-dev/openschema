// src/emit/collection/collectionEmitter.ts
// The `collection` target: the module an app hands to `neoworks.collection()`. It
// pairs the registry path of the schema (from openschema.yaml beside it) with the
// descriptor text exactly as `openschema publish` uploads it, so the descriptor
// an app bundles and the one the registry serves are the same bytes. When the codec
// module is generated too, the export also carries the content type of every
// table, so the SDK can type the resources it builds from the descriptor.

import { buildDescriptor, definesNeoworksTables, publishedDescriptor } from "../descriptor/descriptorEmitter.js";
import type { EmitContext, Emitter, OutputFile } from "../types.js";

export const COLLECTION_FILE = "index.ts";

/** The context option naming the collection, `@scope/name`; the CLI fills it from the manifest. */
export const COLLECTION_OPTION = "collection";

/** The context option naming the codec module to re-export, set when the codec target runs too. */
export const CODEC_MODULE_OPTION = "codecModule";

export class CollectionTargetError extends Error {}

export const collectionEmitter: Emitter = {
  target: "collection",
  fileExtension: "ts",

  emit(context: EmitContext): OutputFile[] {
    const name = context.options[COLLECTION_OPTION];
    if (name === undefined) {
      throw new CollectionTargetError("the collection target needs the schema's registry path; run it through the CLI with an openschema.yaml beside the schema");
    }
    if (!definesNeoworksTables(context.schema)) {
      throw new CollectionTargetError("the collection target needs a schema that defines @neoworks.table models");
    }
    const tables = buildDescriptor({ schema: context.schema, company: null, includePrivate: false, options: {} }).tables;
    const models = tables.map((table) => table.model);
    return [{ path: COLLECTION_FILE, contents: collectionModule(name, publishedDescriptor(context.schema), models, context.options[CODEC_MODULE_OPTION]) }];
  },
};

function collectionModule(name: string, descriptor: string, models: string[], codecModule: string | undefined): string {
  const lines = ["// Generated by openschema (collection target). Do not edit."];
  if (codecModule === undefined) {
    lines.push("", ...untypedCollection(name, descriptor));
  } else {
    lines.push(`export * from './${codecModule}'`, `import type { ${models.join(", ")} } from './${codecModule}'`, "", ...typedCollection(name, descriptor, models));
  }
  lines.push("", "export default collection", "");
  return lines.join("\n");
}

function untypedCollection(name: string, descriptor: string): string[] {
  return [
    "/** Pass to `Neoworks.collection`; the descriptor text is exactly what the registry publishes. */",
    "export const collection = {",
    `\tname: '${name}',`,
    `\tdescriptor: ${JSON.stringify(descriptor)},`,
    "} as const",
  ];
}

/** The `tables` member exists only in the type: it tells the SDK which content type each table has. */
function typedCollection(name: string, descriptor: string, models: string[]): string[] {
  const lines = [
    "/** Pass to `Neoworks.collection`; the descriptor text is exactly what the registry publishes. */",
    "export const collection = {",
    `\tname: '${name}',`,
    `\tdescriptor: ${JSON.stringify(descriptor)},`,
    "} as {",
    `\treadonly name: '${name}'`,
    "\treadonly descriptor: string",
  ];
  lines.push(`\treadonly tables?: { ${models.map((model) => `${model}: ${model}`).join("; ")} }`);
  lines.push("}");
  return lines;
}
