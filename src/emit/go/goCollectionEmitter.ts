// src/emit/go/goCollectionEmitter.ts
// The `go-collection` target: the Go file an app imports to open a Neoworks collection with the Go
// SDK's `collections` package. It holds the content structs in the core's JSON mapping, typed field
// handles for conditions, orders and changes, and the tables of the collection. The SDK half is
// `github.com/neoworks-dev/sdk-go/collections`.

import { buildDescriptor, definesNeoworksTables, publishedDescriptor } from "../descriptor/descriptorEmitter.js";
import type { SchemaDescriptor } from "../descriptor/descriptorTypes.js";
import { COLLECTION_OPTION, COLLECTION_VERSION_OPTION } from "../collection/collectionEmitter.js";
import type { CollectionIdentity } from "../../registry/collectionName.js";
import type { EmitContext, Emitter, OutputFile } from "../types.js";
import { GO_PACKAGE_OPTION } from "./goEmitter.js";
import { handleNames, handlesSource } from "./goCollectionHandles.js";
import { declaredTypeNames, docsOf, modelsSource } from "./goCollectionModels.js";
import { FILE_LEVEL_NAMES, constantsSource, schemaSource, tablesSource } from "./goCollectionTables.js";
import { GoImports } from "./goCollectionTypes.js";
import { GoTargetError } from "./goTargetError.js";

/** The context option that adds the share scope to the collection's scopes; the CLI sets it from --share. */
export const GO_SHARE_OPTION = "share";

const HEADER = "// Code generated by openschema (go-collection target). DO NOT EDIT.";
const GO_PACKAGE_NAME = /^[a-z][a-z0-9_]*$/;
const GO_KEYWORDS: ReadonlySet<string> = new Set([
  "break", "case", "chan", "const", "continue", "default", "defer", "else", "fallthrough", "for", "func", "go",
  "goto", "if", "import", "interface", "map", "package", "range", "return", "select", "struct", "switch", "type", "var",
]);

export { GoTargetError };

export const goCollectionEmitter: Emitter = {
  target: "go-collection",
  fileExtension: "go",

  emit(context: EmitContext): OutputFile[] {
    const identity = collectionIdentityOf(context);
    const descriptor = buildDescriptor({ ...context, company: null });
    rejectNameCollisions(descriptor);
    const packageName = packageNameOf(context, identity);
    const imports = new GoImports();
    const blocks = [
      constantsSource(identity, scopesOf(context)),
      schemaSource(publishedDescriptor(context.schema)),
      ...modelsSource(descriptor, docsOf(context.schema), imports),
      ...handlesSource(descriptor, imports),
      tablesSource(descriptor, imports),
    ];
    return [{ path: `${packageName}.go`, contents: fileSource(packageName, imports, blocks) }];
  },
};

function collectionIdentityOf(context: EmitContext): CollectionIdentity {
  const name = context.options[COLLECTION_OPTION];
  const version = context.options[COLLECTION_VERSION_OPTION];
  if (name === undefined || version === undefined) {
    throw new GoTargetError("the go-collection target needs the schema's registry path and version; run it through the CLI with an openschema.yaml beside the schema");
  }
  if (!definesNeoworksTables(context.schema)) {
    throw new GoTargetError("the go-collection target needs a schema that defines @neoworks.table models");
  }
  return { name, version };
}

function scopesOf(context: EmitContext): string[] {
  if (context.options[GO_SHARE_OPTION] === "true") return ["read", "write", "share"];
  return ["read", "write"];
}

/** The configured package, or the last segment of the collection's name. */
function packageNameOf(context: EmitContext, identity: CollectionIdentity): string {
  const configured = context.options[GO_PACKAGE_OPTION];
  let packageName = configured;
  if (packageName === undefined || packageName === "") {
    packageName = identity.name.slice(identity.name.lastIndexOf("/") + 1).toLowerCase().replace(/[^a-z0-9_]+/g, "");
  }
  if (!GO_PACKAGE_NAME.test(packageName) || GO_KEYWORDS.has(packageName)) {
    throw new GoTargetError(`"${packageName}" is not a usable Go package name; pass one with --package`);
  }
  return packageName;
}

function rejectNameCollisions(descriptor: SchemaDescriptor): void {
  const seen = new Set<string>();
  const names = [...FILE_LEVEL_NAMES, ...declaredTypeNames(descriptor), ...handleNames(descriptor)];
  for (const name of names) {
    if (seen.has(name)) {
      throw new GoTargetError(`the Go name ${name} is declared twice; rename the model, enum or field that produces it`);
    }
    seen.add(name);
  }
}

function fileSource(packageName: string, imports: GoImports, blocks: string[]): string {
  return [HEADER, `package ${packageName}`, importBlock(imports), ...blocks].join("\n\n") + "\n";
}

// gofmt keeps the standard library's imports and the others in separate sorted groups.
function importBlock(imports: GoImports): string {
  const paths = imports.sorted();
  const standard = paths.filter(path => !path.includes("."));
  const others = paths.filter(path => path.includes("."));
  const groups = [standard, others].filter(group => group.length > 0);
  const lines = groups.map(group => group.map(path => `\t"${path}"`).join("\n"));
  return `import (\n${lines.join("\n\n")}\n)`;
}
