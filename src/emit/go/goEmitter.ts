// src/emit/go/goEmitter.ts
// Emits Go structs and enum constants from a resolved schema, formatted the way
// gofmt formats them.

import type { Emitter, EmitContext, OutputFile } from "../types.js";
import type { ResolvedModel, ResolvedField, ResolvedSchema } from "../../resolver/types.js";
import type { TypeExpr, ScalarKind, EnumDecl, ModelDecl } from "../../parser/ast.js";
import {
  baseFieldsToEmit, overlayFieldsToEmit, unwrapNullable, unionAliases, hasDecorator,
  nearestAbstractAncestor, fieldsBeyond, abstractModelOf,
} from "../typeMapping.js";
import { alignRows, docLines, exported } from "./goFormat.js";

const SCALAR_GO: Record<ScalarKind, string> = {
  bool: "bool",
  i8: "int8", i16: "int16", i32: "int32", i64: "int64",
  u8: "uint8", u16: "uint16", u32: "uint32", u64: "uint64",
  f32: "float32", f64: "float64",
  string: "string", bytes: "[]byte", uuid: "string", json: "any",
  date: "string", time: "string", timestamp: "string", duration: "string",
  semver: "string",
};

/** The emit option naming the Go package; `schema` when unset. */
export const GO_PACKAGE_OPTION = "package";

const GENERATED_HEADER = "// Code generated by openschema. DO NOT EDIT.";

export const goEmitter: Emitter = {
  target: "go",
  fileExtension: "go",

  emit(context: EmitContext): OutputFile[] {
    const blocks: string[] = [GENERATED_HEADER, `package ${packageName(context)}`];
    for (const symbol of context.schema.enums.values()) {
      blocks.push(emitEnum(symbol.decl as EnumDecl));
    }
    for (const record of context.schema.records.values()) {
      if (record.isGeneric) continue;
      blocks.push(emitStruct(record, context));
    }
    // Go has no sum type; a union alias is an open `any`.
    for (const { name } of unionAliases(context.schema)) {
      blocks.push(`type ${name} = any`);
    }
    return [{ path: `schema.${this.fileExtension}`, contents: blocks.join("\n\n") + "\n" }];
  },
};

function packageName(context: EmitContext): string {
  const configured = context.options[GO_PACKAGE_OPTION];
  if (configured === undefined || configured === "") return "schema";
  return configured;
}

// Variant names are the values, as in every other non-binary target: JSON and
// databases carry the name, the ordinal is only the schema's identity.
function emitEnum(decl: EnumDecl): string {
  const rows = decl.variants.map(variant => [`${decl.name}${exported(variant.name)}`, `${decl.name} = ${JSON.stringify(variant.name)}`]);
  const consts = alignRows(rows).map(line => `\t${line}`);
  const lines = [...docLines(decl.doc, ""), `type ${decl.name} string`, "", "const (", ...consts, ")"];
  return lines.join("\n");
}

// A model extending an @abstract model embeds that model's struct (Go promotes
// its fields, in Go and in JSON) and declares only the fields it adds.
function emitStruct(record: ResolvedModel, context: EmitContext): string {
  const base = nearestAbstractAncestor(record, context.schema);
  const fields = [
    ...fieldsBeyond(baseFieldsToEmit(record, context), base),
    ...overlayFieldsToEmit(context.schema, record, context.company),
  ];
  const body: string[] = [];
  if (base !== null) body.push(`\t${exported(base.symbol.localName)}`);
  body.push(...fieldBlock(fields, context.schema));
  const doc = docLines((record.symbol.decl as ModelDecl).doc, "");
  return [...doc, `type ${record.symbol.localName} struct {`, ...body, "}"].join("\n");
}

// gofmt aligns name, type and tag columns across a run of plain field lines; a
// doc comment starts a new run, so each documented field begins one.
function fieldBlock(fields: ResolvedField[], schema: ResolvedSchema): string[] {
  const lines: string[] = [];
  let run: string[][] = [];
  for (const field of fields) {
    const doc = docLines(field.doc, "\t");
    if (doc.length > 0) {
      lines.push(...flushRun(run));
      run = [];
      lines.push(...doc);
    }
    run.push(fieldCells(field, schema));
  }
  lines.push(...flushRun(run));
  return lines;
}

function flushRun(run: string[][]): string[] {
  return alignRows(run).map(line => `\t${line}`);
}

function fieldCells(field: ResolvedField, schema: ResolvedSchema): string[] {
  const { inner, nullable } = unwrapNullable(field.type);
  const goType = fieldType(inner, nullable, schema);
  return [exported(field.name), goType, `\`json:"${jsonTag(field, nullable)}"\``];
}

// Nullable values that already have a nil (slices, maps, bytes, any) need no
// pointer; everything else becomes one.
function fieldType(inner: TypeExpr, nullable: boolean, schema: ResolvedSchema): string {
  const goType = mapType(inner, schema);
  if (!nullable) return goType;
  if (hasNil(goType)) return goType;
  return `*${goType}`;
}

function hasNil(goType: string): boolean {
  if (goType === "any") return true;
  if (goType.startsWith("[]")) return true;
  return goType.startsWith("map[");
}

function jsonTag(field: ResolvedField, nullable: boolean): string {
  if (hasDecorator(field.decorators, "invisible")) return "-";
  if (nullable) return `${field.name},omitempty`;
  return field.name;
}

// A value typed as an @abstract model may be any of its subtypes, which Go can
// only hold as `any`.
function isAbstractValue(type: TypeExpr, schema: ResolvedSchema): boolean {
  return abstractModelOf(type, schema) !== null;
}

function mapType(type: TypeExpr, schema: ResolvedSchema): string {
  if (isAbstractValue(type, schema)) return "any";
  switch (type.kind) {
    case "scalar":   return SCALAR_GO[type.scalar];
    case "decimal":  return "string";
    case "named":    return exported(type.path[type.path.length - 1]);
    case "array":    return `[]${mapType(type.element, schema)}`;
    case "map":      return `map[${mapType(type.key, schema)}]${mapType(type.value, schema)}`;
    case "nullable": return `*${mapType(type.inner, schema)}`;
    case "null":     return "any";
    case "file":     return "map[string]any";
    case "union":    return "any";
    case "oneof":    return "any";
  }
}
