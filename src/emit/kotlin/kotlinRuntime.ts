// The serializers and value classes the generated models share, written once per package.
// Each one produces the JSON text the TypeScript SDK's content mapping produces.

export const HEADER = "// Generated by openschema (kotlin target). Do not edit.";

/** Names the runtime file declares in the package; a schema may not declare the same. */
export const RUNTIME_NAMES: readonly string[] = [
  "TimestampSerializer", "Int64AsTextSerializer", "UInt64AsTextSerializer", "Base64UrlBytesSerializer",
  "Semver", "SemverSerializer", "File", "FileVariant", "OneofSerializer",
];

export function runtimeSource(packageName: string): string {
  return RUNTIME_TEMPLATE.replace("__PACKAGE__", packageName);
}

const RUNTIME_TEMPLATE = `${HEADER}
package __PACKAGE__

import kotlin.io.encoding.Base64
import kotlin.time.Instant
import kotlinx.serialization.KSerializer
import kotlinx.serialization.Serializable
import kotlinx.serialization.SerializationException
import kotlinx.serialization.descriptors.PrimitiveKind
import kotlinx.serialization.descriptors.PrimitiveSerialDescriptor
import kotlinx.serialization.descriptors.SerialDescriptor
import kotlinx.serialization.descriptors.buildClassSerialDescriptor
import kotlinx.serialization.encoding.Decoder
import kotlinx.serialization.encoding.Encoder
import kotlinx.serialization.json.Json
import kotlinx.serialization.json.JsonDecoder
import kotlinx.serialization.json.JsonElement
import kotlinx.serialization.json.JsonEncoder
import kotlinx.serialization.json.JsonObject
import kotlinx.serialization.json.jsonObject

/** An instant as ISO 8601 text with milliseconds and a trailing Z, as JavaScript's toISOString writes it. */
object TimestampSerializer : KSerializer<Instant> {
    override val descriptor: SerialDescriptor = PrimitiveSerialDescriptor("neoworks.Timestamp", PrimitiveKind.STRING)

    override fun serialize(encoder: Encoder, value: Instant) {
        encoder.encodeString(millisecondText(value))
    }

    override fun deserialize(decoder: Decoder): Instant {
        return Instant.parse(decoder.decodeString())
    }

    private fun millisecondText(instant: Instant): String {
        val text = instant.toString().removeSuffix("Z")
        val dotIndex = text.indexOf('.')
        if (dotIndex < 0) return text + ".000Z"
        val fraction = text.substring(dotIndex + 1).padEnd(3, '0').take(3)
        return text.substring(0, dotIndex + 1) + fraction + "Z"
    }
}

/** A 64-bit integer as decimal text, which JSON numbers cannot hold exactly. */
object Int64AsTextSerializer : KSerializer<Long> {
    override val descriptor: SerialDescriptor = PrimitiveSerialDescriptor("neoworks.Int64AsText", PrimitiveKind.STRING)

    override fun serialize(encoder: Encoder, value: Long) {
        encoder.encodeString(value.toString())
    }

    override fun deserialize(decoder: Decoder): Long {
        return decoder.decodeString().toLong()
    }
}

object UInt64AsTextSerializer : KSerializer<ULong> {
    override val descriptor: SerialDescriptor = PrimitiveSerialDescriptor("neoworks.UInt64AsText", PrimitiveKind.STRING)

    override fun serialize(encoder: Encoder, value: ULong) {
        encoder.encodeString(value.toString())
    }

    override fun deserialize(decoder: Decoder): ULong {
        return decoder.decodeString().toULong()
    }
}

/** Bytes as unpadded base64url text. */
object Base64UrlBytesSerializer : KSerializer<ByteArray> {
    private val base64 = Base64.UrlSafe.withPadding(Base64.PaddingOption.ABSENT_OPTIONAL)

    override val descriptor: SerialDescriptor = PrimitiveSerialDescriptor("neoworks.Base64UrlBytes", PrimitiveKind.STRING)

    override fun serialize(encoder: Encoder, value: ByteArray) {
        encoder.encodeString(base64.encode(value))
    }

    override fun deserialize(decoder: Decoder): ByteArray {
        return base64.decode(decoder.decodeString())
    }
}

/** A semantic version without pre-release or build suffixes; its JSON form is the text major.minor.patch. */
@Serializable(with = SemverSerializer::class)
data class Semver(val major: Int, val minor: Int, val patch: Int)

object SemverSerializer : KSerializer<Semver> {
    override val descriptor: SerialDescriptor = PrimitiveSerialDescriptor("neoworks.Semver", PrimitiveKind.STRING)

    override fun serialize(encoder: Encoder, value: Semver) {
        encoder.encodeString(value.major.toString() + "." + value.minor + "." + value.patch)
    }

    override fun deserialize(decoder: Decoder): Semver {
        val parts = decoder.decodeString().split('.').map { it.toInt() }
        if (parts.size != 3) throw SerializationException("a semver is major.minor.patch")
        return Semver(parts[0], parts[1], parts[2])
    }
}

/** A File of a row. Sizes are 64-bit, so they are written as decimal text. */
@Serializable
data class File(
    val objectId: String,
    val name: String,
    val mediaType: String,
    @Serializable(with = UInt64AsTextSerializer::class) val size: ULong,
    val variants: Map<String, FileVariant>,
)

@Serializable
data class FileVariant(
    val objectId: String,
    @Serializable(with = UInt64AsTextSerializer::class) val size: ULong,
)

/** A oneof is a JSON object with a single entry: the variant name and its value. JSON only. */
abstract class OneofSerializer<Value : Any>(serialName: String) : KSerializer<Value> {
    override val descriptor: SerialDescriptor = buildClassSerialDescriptor(serialName)

    abstract fun variantName(value: Value): String

    abstract fun encodeVariant(json: Json, value: Value): JsonElement

    abstract fun decodeVariant(json: Json, variantName: String, element: JsonElement): Value

    override fun serialize(encoder: Encoder, value: Value) {
        if (encoder !is JsonEncoder) throw SerializationException("a oneof can only be written as JSON")
        val entry = variantName(value) to encodeVariant(encoder.json, value)
        encoder.encodeJsonElement(JsonObject(mapOf(entry)))
    }

    override fun deserialize(decoder: Decoder): Value {
        if (decoder !is JsonDecoder) throw SerializationException("a oneof can only be read from JSON")
        val entries = decoder.decodeJsonElement().jsonObject
        if (entries.size != 1) throw SerializationException("a oneof holds exactly one variant")
        val entry = entries.entries.single()
        return decodeVariant(decoder.json, entry.key, entry.value)
    }
}
`;
